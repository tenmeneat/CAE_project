function sec = lca_section()
%LCA_SECTION 로어암 대용 빔 단면 (블록 4a). [가정] — COMSOL 파라메트릭 형상(D4·D11)이 정해지면 그 값으로 바꿈.
%   A형 암의 앞·뒤 부재가 같은 사각 중공 단면이라고 둔다. 두께 스윕은 tw를 바꿔서 한다.

sec.b  = 0.050;   % [가정] 부재 폭 (e1 방향) [m]
sec.h  = 0.035;   % [가정] 부재 높이 (e3 방향) [m]
sec.tw = 0.005;   % [가정] 벽 두께 [m] — D11 최소 단면 스윕 변수
end
