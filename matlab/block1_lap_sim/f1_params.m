function p = f1_params()
%F1_PARAMS F1급 랩 시뮬 파라미터 — 방법론 검증 전용 (W2 게이트). 우리 차(F82 M4급)와 무관.
%   [가정] 공개 수치에 대한 기억·추정. [보정] I0(2022 Spa 정상 랩 613개 평균) 속도 프로파일 RMSE가 줄도록 격자 탐색으로
%   정한 값. 경과는 블록1-랩시뮬레이션.md "RMSE 분석" 참고.
%
%   단일 μ(마찰원)로는 실측의 "높은 코너 그립 + 약한 제동"을 동시에 못 맞춰서 마찰 타원(횡 μ, 종 μx)을 쓴다.
%   CdA를 풀면 비현실적으로 커지며(양항비 ~1.9) 직선 손실을 떠안아서 1.2로 고정하고 유효 출력 P로 흡수했다
%   (Spa 긴 직선에서 ERS 전개가 바닥난 뒤 수준). 탐색: μ 1.6–2.2, μx 1.0–1.4, CzA 3–5, P 440–650 kW → RMSE 3.5%.
%   μx가 작은 건 타이어 한계가 아니라 레이스 페이스(브레이크·타이어 관리) + 랩 평균의 제동 램프 흐림 때문.
%   상위 조합들이 서로 대체되므로(μ↔CzA) 절대값은 식별되지 않는다 — F1 제원 추정이 아니다.

p = f82_params();
p.m      = 850;       % [가정] 최소중량 798 kg(드라이버 포함) + 레이스 평균 연료
p.L      = 3.6;       % [가정] 휠베이스 [m]
p.w_rear = 0.54;      % [가정] 뒤 하중 비율
p.h_cg   = 0.28;      % [가정]
p.P      = 560e3;     % [보정] 유효 출력 [W] — ERS 소진 후 수준 (명목 ICE+ERS ~700 kW). 600 kW부터 오차 증가
p.eta    = 0.95;      % [가정]
p.mu     = 1.8;       % [보정] 횡방향 마찰계수 (다운포스는 CzA로 별도)
p.mu_x   = 1.2;       % [보정] 종방향 마찰계수 — 레이스 페이스 제동 + 평균화 흐림 포함
p.CdA    = 1.2;       % [가정] 항력면적 [m^2] (DRS 무시) — 고정
p.CzA    = 4.0;       % [보정] 다운포스면적 [m^2] (양항비 3.3)
p.gn_max = 100;       % 하중 민감도 상한 끔 (다운포스를 쓰므로)
p.vmax   = 100;       % [m/s] 속도 제한 없음에 가까움
end
