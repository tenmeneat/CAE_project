function p = f82_params()
%F82_PARAMS BMW F82 M4급 랩 시뮬 파라미터 (D3). SI 단위.
%   [확정] 출처가 문서에 있는 값
%   [지정] 사용자가 정한 값 (문헌·실측 근거 없음, 의사결정으로 고정)
%   [가정] 근거 없는 추정 — 이 값으로 계산하지만 확정값이 아니다. W2 방법론·차급 검증에서 보정할 노브.

p.g     = 9.81;
p.m     = 1642;       % [확정] 공차중량 DCT, BMW 공식 [R15] (블록2-풀카-액티브제어.md)
p.L     = 2.812;      % [확정] 휠베이스 [m] [R16]
p.w_rear = 0.477;     % [확정] 축하중 앞 52.3 : 뒤 47.7 (DCT, 공차) [R15]
p.h_cg  = 0.49;       % [지정] 무게중심 높이 [m] — 사용자 지정, D3의 해당 항목을 닫음
p.mu    = 1.10;       % [지정] 타이어 마찰계수 (255/40 ZR18 / 275/40 ZR18) — 사용자 지정. 결과에 가장 민감
p.mu_x  = p.mu;       % [지정] 종방향 = 횡방향 (마찰원). F1 검증에서만 분리 (f1_params)
p.P     = 317e3;      % [가정] 엔진 출력 [W] (M4 431PS 기준 기억값, 공식 확인 필요)
p.eta   = 0.90;       % [가정] 구동계 효율
p.gn_max = 1.2;       % [가정] 압축 구간 법선 가속도 상한 [g 배수] — 타이어 하중 민감도(하중↑ → μ↓) 대용. 1.0이면 압축 이득 없음
p.rho   = 1.20;       % 공기 밀도 [kg/m^3] (표준값)
p.CdA   = 0.75;       % [가정] 항력면적 [m^2] (Cd≈0.34 × A≈2.2)
p.CzA   = 0;          % 다운포스면적 [m^2]. 양산차는 0으로 무시 (F1/GT 검증용 파라미터에서만 사용)
p.vmax  = 250/3.6;    % [가정] 전자 제한 속도 [m/s] (양산 M4 250 km/h)
% 시나리오 B (컴포트) 가속도 상한 — D17 추천값, 미결. 문헌 근거 보강 여부 미정
p.ay_cap = 0.4 * p.g; % [가정] 횡가속도 상한 [m/s^2]
p.ax_cap = 0.3 * p.g; % [가정] 종가속도 상한 [m/s^2]

% ── 블록 2 풀카 (D3). 실측값은 Michelin SIMIX F82 M4 데이터셋(유료)뿐이라 아래는 전부 문헌 범위 안의 선택값.
%    k·c는 직접 정하지 않고 승차 주파수·감쇠비에서 build_state_space가 역산한다 (휠 기준, MR과 무관).
p.tf    = 1.579;      % [확정] 앞 트레드 [m] [R16]
p.tr    = 1.603;      % [확정] 뒤 트레드 [m] [R16]
p.f_ride = [1.6 1.8]; % [지정] 승차 주파수 앞/뒤 [Hz] (스포츠카 1.6–2.3 Hz 하단, 뒤를 높게 = flat ride). 2026-11-03
p.zeta  = 0.30;       % [지정] Passive 감쇠비 (문헌 0.25–0.45). Passive 기준선이라 민감도 필요. 2026-11-03
p.kt    = 280e3;      % [가정] 타이어 수직 강성 [N/m] (승용 200–320 N/mm, 저편평비라 위쪽)
p.m_uf  = 45;         % [가정] 앞 비현가 질량/코너 [kg] (휠·타이어·브레이크·너클 합산 추정, 40–55)
p.m_ur  = 50;         % [가정] 뒤 비현가 질량/코너 [kg] (+드라이브샤프트 절반)
ms_ab  = (p.m - 2*p.m_uf - 2*p.m_ur) * p.L^2 * p.w_rear * (1 - p.w_rear);
p.Iyy   = 1.0 * ms_ab; % [가정] 피치 관성 [kg·m^2] = 동적지수 DI·m_s·a·b, DI = 1 (회전반경 ≈0.5 L, 앞뒤 승차 모드 분리)
p.roll_grad = 3.0;    % [가정] 롤 구배 목표 [deg/g] (고성능 로드카 ≈3.0, 스포츠카 ≈4.2 — 2차 출처 표) → 스태빌라이저 역산
p.lltd_f = 0.57;      % [가정] 앞 횡하중 이동 비율 (경험칙: 정적 앞 하중 52.3% + 5%p, 언더스티어 쪽)
p.Ixx   = 500;       % [가정] 현가 질량 롤 관성 [kg·m^2] (회전반경 ≈0.6 m, 근거 약함)
end
