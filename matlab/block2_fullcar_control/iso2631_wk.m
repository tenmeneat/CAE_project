function H = iso2631_wk()
%ISO2631_WK ISO 2631-1:1997 수직 진동 주파수 가중 Wk (부록 A) 전달함수 (tf, s 영역).
%   H = ISO2631_WK()   a_w(t) = lsim(H, a(t), t)
%   대역 제한(고역 0.4 Hz, 저역 100 Hz, 2차 Butterworth) × 가속도-속도 전이(f3 = f4 = 12.5 Hz, Q4 = 0.63)
%   × 상향 계단(f5 = 2.37 Hz, Q5 = 0.91, f6 = 3.35 Hz, Q6 = 0.91).

w = 2*pi * [0.4 100 12.5 12.5 2.37 3.35];
s = tf('s');
Hh = s^2 / (s^2 + sqrt(2)*w(1)*s + w(1)^2);
Hl = w(2)^2 / (s^2 + sqrt(2)*w(2)*s + w(2)^2);
Ht = (1 + s/w(3)) / (1 + s/(0.63*w(4)) + s^2/w(4)^2);
Hs = (1 + s/(0.91*w(5)) + s^2/w(5)^2) / (1 + s/(0.91*w(6)) + s^2/w(6)^2) * (w(5)/w(6))^2;
H = Hh * Hl * Ht * Hs;
end
