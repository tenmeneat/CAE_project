function ap = actuator_params()
%ACTUATOR_PARAMS 리니어 액추에이터 열 해석 입력 (블록 4b, D15). 전부 [가정] — D15(액추에이터 사양 출처) 확정 시 교체.
%   원통형 리니어 액추에이터: 코일(반경 r_c, 길이 L_c) → 포팅층(두께 t_pot) → 알루미늄 하우징(t_h) → 외표면 대류 h.

ap.Kf    = 80;      % [가정] 힘 상수 [N/A] (포화 3.7 kN에서 약 46 A)
ap.Rcoil = 0.50;    % [가정] 코일 저항 [Ω], Tlim 기준 (보수적 고정)
ap.Tamb  = 40;      % [가정] 휠하우스 주변 온도 [°C]
ap.Tlim  = 155;     % F급 절연 한계 [°C] (블록 4b 노트)
ap.F_sat = 3.7e3;   % [가정] 포화 힘 [N], 액추에이터 기준 (Audi A8 공개값에서 출발, 기준 미확인 — D15)
ap.r_c   = 0.040;   % [가정] 코일 외반경 [m]
ap.L_c   = 0.150;   % [가정] 코일 길이 [m]
ap.t_pot = 1.0e-3;  % [가정] 포팅(에폭시) 두께 [m]
ap.k_pot = 1.0;     % [가정] 포팅 열전도 [W/m·K] (충전 에폭시 0.5–2)
ap.t_h   = 4.0e-3;  % [가정] 하우징 두께 [m]
ap.k_h   = 167;     % 알루미늄 6061 열전도 [W/m·K]
ap.h     = 25;      % [가정] 외표면 대류계수 [W/m²·K] (자연~약한 강제대류 10–100, 민감도 대상)
end
